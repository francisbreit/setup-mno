get_auth_token() {
    #echo "[INFO] Autenticando no Portainer..."
    echo -e "XXX\n48\nAUTENTICANDO NO PORTAINER... 3/4  \nXXX"
    RESPONSE=$(curl -sS -X POST "https://$PORTAINER_URL/api/auth" \
