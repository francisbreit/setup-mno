msg() {
    # As funções de coleta são chamadas por substituição de comando. Direcionar
    # a interface para stderr mantém o Whiptail visível no terminal/ttyd.
    whiptail --title "SETUP MNO CONTROL CENTER" --msgbox "$1" 14 78 1>&2
